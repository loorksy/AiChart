def _ulcer_index(frame: Frame, params: Mapping[str, Any]) -> float:
    period = _period(params)
    values = _require(frame.raw("close"), period)[-period:]
    drawdown = [
        100.0 * (divide(value, peak) - 1.0)
        for value, peak in zip(values, cummax(values), strict=True)
    ]
    return sqrt(nanmean([value * value for value in drawdown]))


def _parkinson_volatility(frame: Frame, params: Mapping[str, Any]) -> float:
    period = _period(params)
    high = _require(frame.raw("high"), period)[-period:]
    low = replace_zero_with_nan(_require(frame.raw("low"), period)[-period:])
    ratios = [log(divide(h, low_value)) for h, low_value in zip(high, low, strict=True)]
    variance = nanmean([value * value for value in ratios]) / (4.0 * math.log(2.0))
    return math.sqrt(max(0.0, variance) * TRADING_DAYS_PER_YEAR)


def _garman_klass_volatility(frame: Frame, params: Mapping[str, Any]) -> float:
    period = _period(params)
    high = _require(frame.raw("high"), period)[-period:]
    low = replace_zero_with_nan(_require(frame.raw("low"), period)[-period:])
    open_values = replace_zero_with_nan(_require(frame.raw("open"), period)[-period:])
    close = _require(frame.raw("close"), period)[-period:]
    coefficient = 2.0 * math.log(2.0) - 1.0
    variance = [
        0.5 * log(divide(h, low_value)) ** 2 - coefficient * log(divide(c, o)) ** 2
        for h, low_value, c, o in zip(high, low, close, open_values, strict=True)
    ]
    return math.sqrt(max(0.0, nanmean(variance)) * TRADING_DAYS_PER_YEAR)


def _amihud_illiquidity(frame: Frame, params: Mapping[str, Any]) -> float:
    period = _period(params)
    close = _require(frame.raw("close"), period + 1)
    volume = frame.raw("volume")[-period:]
    returns = [abs(value) for value in pct_change(close)][-period:]
    traded_value = replace_zero_with_nan(
        [c * v for c, v in zip(close[-period:], volume, strict=True)]
    )
    # `mean`, not `nanmean`: upstream drops to raw arrays here, so a single
    # untraded bar makes the whole factor NaN. That is the answer, not a gap.
    return mean([divide(r, t) for r, t in zip(returns, traded_value, strict=True)])
