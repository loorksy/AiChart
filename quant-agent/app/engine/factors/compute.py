# Upstream's global parameter bounds. Note that individual kernels pass a
# `minimum` of 1 where a one-bar lookback is meaningful (`smooth_k`,
# `slope_period`, `k_period`, `d_period`, KAMA's `fast_period`).
MIN_PERIOD = 2
MAX_PERIOD = 5000

TRADING_DAYS_PER_YEAR = 252.0

