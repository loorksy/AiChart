def _period(params: Mapping[str, Any], key: str = "period", minimum: int = MIN_PERIOD) -> int:
    """Upstream's `int(params.get(key) or minimum)`.

    The `or` matters: a falsy value (0, "", None, False) falls back to the
    minimum, while a truthy non-integer string still goes through `int()` and
    fails as `factor.invalidParameter`.
    """
    try:
        value = int(params.get(key) or minimum)
    except (TypeError, ValueError) as exc:
        raise FactorError("factor.invalidParameter") from exc
    if value < minimum or value > MAX_PERIOD:
        raise FactorError("factor.invalidParameter")
    return value


def _positive_float(params: Mapping[str, Any], key: str, default: float) -> float:
    try:
        value = float(params.get(key, default))
    except (TypeError, ValueError) as exc:
        raise FactorError("factor.invalidParameter") from exc
    if not math.isfinite(value) or value <= 0:
        raise FactorError("factor.invalidParameter")
    return value


def _choice(params: Mapping[str, Any], key: str, allowed: set[str], default: str) -> str:
    value = str(params.get(key, default) or default).strip().lower()
    if value not in allowed:
        raise FactorError("factor.invalidParameter")
    return value


def _require(values: Sequence[float], count: int) -> list[float]:
    clean = nan_filter(values)
    if len(clean) < count:
        raise FactorError("factor.insufficientHistory")
    return clean


def _ema_values(values: Sequence[float], period: int) -> list[float]:
    """The system-wide EMA convention: SMA seed at index `period - 1`, then
    `2 / (period + 1)`. Every EMA-derived factor goes through here."""
    clean = nan_filter(values)
    if len(clean) < period:
        raise FactorError("factor.insufficientHistory")
    out = [NAN] * len(clean)
    out[period - 1] = sum(clean[:period]) / period
    multiplier = 2.0 / (period + 1.0)
    for index in range(period, len(clean)):
        out[index] = (clean[index] - out[index - 1]) * multiplier + out[index - 1]
    return out


def _wma_values(values: Sequence[float], period: int) -> list[float]:
    """Linearly weighted moving average — only `hma` uses it."""
    clean = _require(values, period)
    weights = [float(index) for index in range(1, period + 1)]
    weight_sum = sum(weights)
    out = [NAN] * len(clean)
    for index in range(period - 1, len(clean)):
        window = clean[index - period + 1 : index + 1]
        out[index] = sum(a * b for a, b in zip(window, weights, strict=True)) / weight_sum
    return out


def _true_range(frame: Frame) -> list[float]:
    """Wilder's true range, INCLUDING bar 0.

    Upstream stacks the three candidate ranges and takes a row-wise max that
    skips NaN, so bar 0 — where both previous-close terms are NaN — survives
    as `high - low`. Reproducing that offset is what keeps `atr` and friends
    aligned with upstream instead of with TA-Lib.
    """
    high = frame.raw("high")
    low = frame.raw("low")
    close = frame.raw("close")
    previous = shift(close, 1)
    candidates = [
        [a - b for a, b in zip(high, low, strict=True)],
        [abs(a - b) for a, b in zip(high, previous, strict=True)],
        [abs(a - b) for a, b in zip(low, previous, strict=True)],
    ]
    stacked = row_max(row_max(candidates[0], candidates[1]), candidates[2])
    return dropna(stacked)


def _wilder_last(values: Sequence[float], period: int) -> float:
    clean = _require(values, period)
    result = sum(clean[:period]) / period
    for value in clean[period:]:
        result = (result * (period - 1) + value) / period
    return result


