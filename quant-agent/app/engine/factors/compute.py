def _chaikin(frame: Frame, params: Mapping[str, Any]) -> float:
    fast = _period(params, "fast_period")
    slow = _period(params, "slow_period")
    if fast >= slow:
        raise FactorError("factor.invalidParameter")
    values = _ad_series(frame)
    fast_value = _ema_values(values, fast)[-1]
    slow_value = _ema_values(values, slow)[-1]
    scale = nanmean(nan_filter(frame.raw("volume"))[-slow:])
