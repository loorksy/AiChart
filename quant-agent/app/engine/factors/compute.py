"""The 61 built-in factor kernels, kept in upstream's declaration order so the
two files can be read side by side.

Ported from QuantDinger (https://github.com/OpenByteInc/QuantDinger),
Copyright Open Byte Inc., licensed under the Apache License, Version 2.0
(http://www.apache.org/licenses/LICENSE-2.0). Source:
`backend_api_python/app/services/factors/registry.py` (every `_`-prefixed
kernel and guard helper between lines 280 and 1005).

Changed on port: pandas/numpy are unavailable here, so every kernel was
rewritten against `app/engine/factors/frame.py`'s stdlib stand-ins. The
translation is mechanical and the numbers are frozen against upstream's own
output in `tests/test_factors_golden.json`, which was generated by running the
upstream implementation (pandas 3.0.5) over the same synthetic bars.

Nothing was "cleaned up" in the process. Six upstream behaviours look like
defects, are load-bearing for the numbers, and are reproduced deliberately:

  * **Bar-0 true range.** `_true_range` takes a row-wise max that SKIPS NaN,
    so row 0 — whose two previous-close terms are NaN — yields `high - low`
    instead of being dropped. The TR series is therefore as long as the frame
    and one element longer than TA-Lib's. `atr`, `atr_pct`, `supertrend`,
    `vortex`, `choppiness` and `keltner_channels` all inherit that offset.
  * **Mixed `ddof`.** `bollinger_bands` uses the population deviation;
    `realized_volatility`, `volume_zscore` and `mean_reversion_zscore` use the
    sample one. They are not unified.
  * **The ADX loop.** `_adx_components` iterates from `period - 1` but only
    advances the Wilder sums `if index >= period`, so the first DX comes off
    the raw window sums; and the returned `plus_di`/`minus_di` are the last
    iteration's leaked loop locals rather than a separate final computation.
  * **The KDJ seed.** K and D start at 50.0 (the Chinese convention, not
    Wilder's), `rsv` falls back to 50.0 on a degenerate range, and the loop
    runs over the ENTIRE frame rather than a bounded window.
  * **NaN poisoning in `amihud_illiquidity`.** It drops to raw arrays before
    averaging, so one bar with zero traded value makes the whole factor NaN.
    That is the signal (the bar did not trade), not a bug to paper over.
  * **SMA-seeded EMA.** `_ema_values` seeds at index `period - 1` with the
    simple mean of the first `period` observations, then applies
    `2 / (period + 1)`. Every EMA-derived factor inherits that seed.
"""

