def _return(frame: Frame, params: Mapping[str, Any]) -> float:
    period = _period(params)
    values = nan_filter(frame.raw("close"))
    if len(values) <= period:
        raise FactorError("factor.insufficientHistory")
    return divide(values[-1], values[-period - 1]) - 1.0


def _realized_vol(frame: Frame, params: Mapping[str, Any]) -> float:
    period = _period(params)
    returns = dropna(pct_change(nan_filter(frame.raw("close"))))
    if len(returns) < period:
        raise FactorError("factor.insufficientHistory")
    return stdev(returns[-period:], ddof=1) * math.sqrt(TRADING_DAYS_PER_YEAR)


def _ema_slope(frame: Frame, params: Mapping[str, Any]) -> float:
    period = _period(params)
    slope_period = _period(params, "slope_period", minimum=1)
    values = _require(frame.raw("close"), period + slope_period)
    ema = _ema_values(values, period)
    base = ema[-slope_period - 1]
    return divide(ema[-1], base) - 1.0 if base else NAN


def _atr_pct(frame: Frame, params: Mapping[str, Any]) -> float:
    last_close = frame.raw("close")[-1]
    return divide(_atr(frame, params), last_close) if last_close else NAN


def _zscore_last(series: Sequence[float], params: Mapping[str, Any]) -> float:
    period = _period(params)
    values = nan_filter(series)
    if len(values) < period:
        raise FactorError("factor.insufficientHistory")
    window = values[-period:]
    deviation = stdev(window, ddof=1)
    if not deviation > 0:
        return 0.0
    return (window[-1] - sum(window) / len(window)) / deviation


def _turnover(frame: Frame, params: Mapping[str, Any]) -> float:
    period = _period(params)
    values = nan_filter(frame.product("close", "volume"))
    if len(values) < period:
        raise FactorError("factor.insufficientHistory")
    return sum(values[-period:]) / period


def _last_value(frame: Frame, field: str) -> float:
    values = nan_filter(frame.raw(field))
    if not values:
        raise FactorError("factor.insufficientHistory")
    return values[-1]


def _ratio_last(frame: Frame, numerator: str, denominator: str) -> float:
    numerator_value = _last_value(frame, numerator)
    denominator_value = _last_value(frame, denominator)
    return divide(numerator_value, denominator_value) if denominator_value else NAN


def _growth_last(frame: Frame, field: str) -> float:
    values = nan_filter(frame.raw(field))
    if len(values) < 2:
        raise FactorError("factor.insufficientHistory")
    previous = values[-2]
    return divide(values[-1], previous) - 1.0 if previous else NAN


